export type IconName = keyof typeof iconPaths;

const svgNamespace = "http://www.w3.org/2000/svg";

// Built with DOMParser rather than innerHTML so the extension passes
// AMO's unsafe-assignment lint without exceptions.
export function createIcon(name: IconName): SVGSVGElement {
  const markup = `<svg xmlns="${svgNamespace}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${iconPaths[name]}</svg>`;
  const parsed = new DOMParser().parseFromString(markup, "image/svg+xml");

  return document.importNode(
    parsed.documentElement,
    true,
  ) as unknown as SVGSVGElement;
}

export function setIcon(button: HTMLButtonElement, name: IconName): void {
  button.replaceChildren(createIcon(name));
}
